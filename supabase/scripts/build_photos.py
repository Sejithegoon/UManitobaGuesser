#!/usr/bin/env python3
"""
build_photos.py - make the server-game copies of the location photos.

For every location in locations/locations.json (same validation and
--duplicates choice as import_locations.py) this:
  * gives it a random, opaque photo key (kept in a git-ignored mapping file,
    so re-runs reuse the same keys),
  * writes a resized, metadata-free copy to   locations/p/<key>.jpg
    (longest side <= 1600 px, JPEG quality 80, EXIF/GPS stripped, rotation
    applied) - the originals in locations/IMG/ are NOT touched,
  * writes supabase/seed/photo_keys.local.sql, which sets
    public.locations.public_key to those keys (run it in the SQL Editor).

The key -> location mapping must never be published: it would turn the
opaque filenames back into answers. Both generated files are git-ignored.

Usage (from the project folder):
    python supabase/scripts/build_photos.py --duplicates last
"""
import argparse
import json
import secrets
import sys
from pathlib import Path

from PIL import Image, ImageOps

sys.path.insert(0, str(Path(__file__).resolve().parent))
from import_locations import ROOT, IMG_DIR, load_and_validate, sql_literal  # noqa: E402

OUT_DIR = ROOT / "locations" / "p"
KEYS_JSON = ROOT / "supabase" / "seed" / "photo_keys.local.json"
KEYS_SQL = ROOT / "supabase" / "seed" / "photo_keys.local.sql"
MAX_SIDE = 1600
QUALITY = 80


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--duplicates", choices=["fail", "first", "last"], default="fail")
    args = ap.parse_args()

    rows, missing, _ = load_and_validate(args.duplicates)
    if missing:
        sys.exit(f"ERROR: no photo for: {', '.join(missing)}")

    keys = json.loads(KEYS_JSON.read_text(encoding="utf-8")) if KEYS_JSON.exists() else {}
    OUT_DIR.mkdir(parents=True, exist_ok=True)

    before = after = 0
    for name, _, _ in rows:
        key = keys.get(name) or secrets.token_hex(16)
        keys[name] = key
        src, dst = IMG_DIR / f"{name}.jpg", OUT_DIR / f"{key}.jpg"
        before += src.stat().st_size
        if not dst.exists() or dst.stat().st_mtime < src.stat().st_mtime:
            with Image.open(src) as im:
                im = ImageOps.exif_transpose(im).convert("RGB")
                im.thumbnail((MAX_SIDE, MAX_SIDE), Image.LANCZOS)
                im.save(dst, "JPEG", quality=QUALITY, optimize=True, progressive=True)  # no exif= -> stripped
        after += dst.stat().st_size

    # Report copies that no longer belong to any location (not deleted automatically)
    valid = {f"{k}.jpg" for k in keys.values()}
    stale = sorted(p.name for p in OUT_DIR.glob("*.jpg") if p.name not in valid)

    KEYS_JSON.parent.mkdir(parents=True, exist_ok=True)
    KEYS_JSON.write_text(json.dumps(keys, indent=2, sort_keys=True), encoding="utf-8", newline="\n")

    values = ",\n".join(f"  ({sql_literal(n)}, {sql_literal(keys[n])})" for n, _, _ in rows)
    KEYS_SQL.write_text(f"""-- GENERATED by supabase/scripts/build_photos.py - do not edit, do not commit.
-- Points each location at its opaque photo locations/p/<public_key>.jpg
begin;
update public.locations l set public_key = v.key
  from (values
{values}
  ) as v(name, key)
 where l.legacy_name = v.name and l.public_key is distinct from v.key;

do $verify$
declare n int;
begin
  select count(*) into n from public.locations l
    join (values
{values}
    ) as v(name, key) on v.name = l.legacy_name and v.key = l.public_key;
  if n <> {len(rows)} then
    raise exception 'photo key check failed: % of {len(rows)} locations point at their photo', n;
  end if;
end
$verify$;
commit;
""", encoding="utf-8", newline="\n")

    print(f"OK: {len(rows)} photos in locations/p/ "
          f"({before / 1e6:.1f} MB originals -> {after / 1e6:.1f} MB copies, avg {after / len(rows) / 1e3:.0f} KB)",
          file=sys.stderr)
    if stale:
        print(f"note: copies not used by any location: {', '.join(stale)}", file=sys.stderr)
    print(f"wrote {KEYS_SQL.relative_to(ROOT)} and {KEYS_JSON.relative_to(ROOT)} (both git-ignored)", file=sys.stderr)


if __name__ == "__main__":
    main()
